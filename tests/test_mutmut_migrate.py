def factory_before() -> str | None:
    """The factory as it stood before the slice: the parent of the oldest commit that adds the slice's module."""
    added = subprocess.run(["git", "log", "--diff-filter=A", "--format=%H", "--", "/".join(FIRST)], cwd=ROOT, text=True,
                           capture_output=True, check=False, timeout=60).stdout.split()
    if not added:
        return None
    parent = subprocess.run(["git", "rev-parse", "--verify", "-q", f"{added[-1]}^{{commit}}^"], cwd=ROOT, text=True,
                            capture_output=True, check=False, timeout=60)
    return parent.stdout.strip() or None


BEFORE = factory_before()


def squashed(text: str) -> str:
    return " ".join(text.split())


def catch_up() -> str:
    text = FRAGMENT.read_text(encoding="utf-8")
    (paragraph,) = [block for block in text.split("\n\n") if block.startswith("**Catch-up.**")]
    return squashed(paragraph)


def migrate(repo: Path, factory: Path) -> subprocess.CompletedProcess[str]:
    env = os.environ | {"SLIPWAI_INDEX": "http://127.0.0.1:9/unreachable", "GIT_AUTHOR_NAME": "t",
                        "GIT_AUTHOR_EMAIL": "t@local", "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@local"}
    return subprocess.run([str(factory / "slipwai"), "migrate"], cwd=repo, env=env, text=True, capture_output=True,
                          timeout=300)


def clean_environment() -> dict[str, str]:
    return {k: v for k, v in os.environ.items() if k not in CI_MARKERS + MAKE_STATE + GIT_STATE + ("SINCE",)}


class FragmentTest(unittest.TestCase):
    def test_e1_the_fragment_is_minor_and_its_catch_up_stands_alone_and_says_what_it_asks(self) -> None:
        text = FRAGMENT.read_text(encoding="utf-8")
        self.assertEqual(text.splitlines()[0], "MINOR")
        self.assertTrue(re.match(r"^\*\*[^*]+[.!?]\*\*", text.split("\n\n")[1]), "a bold lead sentence")
        note = catch_up()
        for words in CATCH_UP_WORDS:
            self.assertIn(words, note)
        self.assertNotIn("follow-on", note)
        self.assertNotIn("S42", note)
        self.assertNotIn("Pragma forms other than", note, "a pragma with a reason or a colon is not flagged")
        for words in FAILED_PRAGMAS:
            self.assertIn(words, note)

    def test_e1_both_paragraphs_the_note_and_the_skill_name_the_same_settings_and_pragma_words(self) -> None:
        """The list is written once and checked in each place that says what fails."""
        first = squashed(FRAGMENT.read_text(encoding="utf-8").split("\n\n")[1])
        places = {"first paragraph": first, "catch-up": catch_up()}
        for path in SAYS_WHAT_FAILS[1:]:
            places[path] = squashed(re.sub(r"^# ?", "", (ROOT / path).read_text(encoding="utf-8"), flags=re.M))
        for place, text in places.items():
            for words in FAILED_SETTINGS + FAILED_PRAGMAS:
                with self.subTest(place=place, words=words):
                    self.assertIn(words, text)

    def test_e1_the_body_says_what_is_true_now_that_the_wrapper_runs_mutmut(self) -> None:
        body = squashed(FRAGMENT.read_text(encoding="utf-8").split("\n\n")[1])
        for words in ("`mutants/<file>.meta`", "`make mutation` mutates only the production files",
                      "`make mutation-full` is the sweep", "killed", "default Python starter"):
            self.assertIn(words, body)
        for stale in ("does not run mutmut yet", "still refuses a changed Python", "still exits 2"):
            self.assertNotIn(stale, body)


class MigrateTest(FactoryTestCase):
    @classmethod
    def setUpClass(cls) -> None:
        super().setUpClass()
        if BEFORE is None:
            raise AssertionError("the factory as it stood before the mutmut slice is not in this clone's history: "
                                 "the migrate examples would pass by being skipped")

    def old_project(self, directory: str, backend: str = "python", added: tuple[str, ...] = ()) -> Path:
        """A project the factory before the slice generated: `git archive` of that commit and its own `generate`."""
        old = Path(directory) / "factory-before"
        old.mkdir()
        archive = subprocess.run(["git", "archive", BEFORE or "HEAD"], cwd=ROOT, capture_output=True, check=True,
                                 timeout=120).stdout
        subprocess.run(["tar", "-x", "-C", str(old)], input=archive, check=True, timeout=120)
        subprocess.run([str(old / "slipwai"), "generate", "product", "--profile", "standard", "--backend", backend,
                        "--frontend", "none", "--http", "none", "--output", directory, "--skip-checks"], check=True,
                       capture_output=True, timeout=300)
        repo = Path(directory) / "product"
        for name in added:
            if repo_git(repo, "status", "--porcelain").strip():
                commit_all(repo, "before " + name)
            subprocess.run([str(old / "slipwai"), "add-service", name, "--language", "python"], cwd=repo, check=True,
                           capture_output=True, timeout=300)
        return repo

    def migrated(self, directory: str, repo: Path) -> subprocess.CompletedProcess[str]:
        if repo_git(repo, "status", "--porcelain").strip():
            commit_all(repo, "as the old factory left it")
        factory = newer_factory(Path(directory), "\n## A section a newer factory added\n")
        shutil.copytree(ROOT / "changelog.d", factory / "changelog.d")  # the fragments are the unreleased entry
        return migrate(repo, factory)

    def test_e2_a_python_project_gains_the_pin_the_table_the_wrapper_and_the_ignore_line(self) -> None:
        rules = importlib.import_module("verify_scoped.rules")
        with tempfile.TemporaryDirectory() as directory:
            repo = self.old_project(directory)
            self.assertFalse((repo / "/".join(WRAPPER)).exists(), "the factory as it was had no such script")
            result = self.migrated(directory, repo)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            manifest = tomllib.loads((repo / "apps/service/pyproject.toml").read_text(encoding="utf-8"))
            self.assertEqual(manifest["dependency-groups"]["dev"].count(PIN), 1)
            self.assertEqual(manifest["tool"]["mutmut"], TABLE)
            self.assertTrue((repo / "/".join(WRAPPER)).stat().st_mode & 0o100)
            self.assertIn("apps/*/mutants/", (repo / ".gitignore").read_text(encoding="utf-8").splitlines())
            makefile = repo / "Makefile"
            self.assertIn("\tpython3 scripts/mutmut-mutation.py apps/service\n", makefile.read_text(encoding="utf-8"))
            self.assertIsNone(rules.text_problem(str(makefile), str(repo / "scripts/verify_scoped/rules.json"), {}),
                              "the scoped gate would be broadened: rules.json is not the Makefile's digest")
            self.assertEqual(repo_git(repo, "status", "--porcelain").strip(), "")
            self.assertIn(catch_up().removeprefix("**Catch-up.**").strip(), squashed(
                (repo / ".slipwai/catch-up.md").read_text(encoding="utf-8")), "the Catch-up reaches the project")

    def test_e3_a_hand_edited_manifest_keeps_its_edit_and_the_lock_follows_the_catch_up(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            repo = self.old_project(directory)
            manifest = repo / "apps/service/pyproject.toml"
            text = manifest.read_text(encoding="utf-8")
            self.assertIn('  "ruff==0.16.3",\n]', text)
            manifest.write_text(text.replace('  "ruff==0.16.3",\n]', '  "ruff==0.16.3",\n  "tomli-w==1.2.0",\n]', 1),
                                encoding="utf-8")
            commit_all(repo, "the product's own dependency")
            result = self.migrated(directory, repo)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            dev = tomllib.loads(manifest.read_text(encoding="utf-8"))["dependency-groups"]["dev"]
            self.assertIn("tomli-w==1.2.0", dev)
            self.assertIn(PIN, dev)
            self.assertEqual(tomllib.loads(manifest.read_text(encoding="utf-8"))["tool"]["mutmut"], TABLE)
            self.assertEqual(repo_git(repo, "status", "--porcelain").strip(), "")
            if shutil.which("uv") is None:
                return
            # Before the lock is redone the manifest and the lock disagree, and `make mutation` says so (AC-S42-12).
            module = next((repo / "apps/service/src").rglob("*.py"))
            module.write_text(module.read_text(encoding="utf-8") + "\n# the product's own line\n", encoding="utf-8")
            done = subprocess.run(["make", "mutation", "SINCE=HEAD"], cwd=repo, env=clean_environment(), text=True,
                                  capture_output=True, timeout=300)
            self.assertEqual(done.returncode, 2, done.stdout + done.stderr)
            self.assertIn("apps/service/uv.lock does not agree with apps/service/pyproject.toml; run uv lock "
                          "--project apps/service", done.stdout + done.stderr)
            relocked = subprocess.run(["uv", "lock", "--project", "apps/service"], cwd=repo, env=clean_environment(),
                                      text=True, capture_output=True, timeout=600)
            if relocked.returncode != 0 and any(word in relocked.stderr.lower() for word in UV_UNREACHABLE):
                return  # `uv lock` resolves against an index: without the network the step is the person's, not ours
            self.assertEqual(relocked.returncode, 0, relocked.stdout + relocked.stderr)
            checked = subprocess.run(["uv", "lock", "--check", "--project", "apps/service"], cwd=repo,
                                     env=clean_environment(), text=True, capture_output=True, timeout=300)
            self.assertEqual(checked.returncode, 0, checked.stdout + checked.stderr)

    def test_e3_a_dependency_of_the_projects_own_with_the_lock_redone_is_listed_as_a_conflict_the_catch_up_settles(
            self) -> None:
        """A service whose manifest and lock the project changed (no `add-service`) conflicts like an added one."""
        if shutil.which("uv") is None:
            self.skipTest("uv is not on PATH: the project's own relocked dependency cannot be made")
        with tempfile.TemporaryDirectory() as directory:
            repo = self.old_project(directory)
            manifest = repo / "apps/service/pyproject.toml"
            relocked = subprocess.run(["uv", "add", "--dev", "--project", "apps/service", "iniconfig==2.1.0"], cwd=repo,
                                      env=clean_environment(), text=True, capture_output=True, timeout=600)
            if relocked.returncode != 0 and any(word in relocked.stderr.lower() for word in UV_UNREACHABLE):
                self.skipTest("uv lock resolves against an index and there is no network")
            self.assertEqual(relocked.returncode, 0, relocked.stdout + relocked.stderr)
            commit_all(repo, "the product's own dependency, relocked")
            result = self.migrated(directory, repo)
            self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
            reported = set(re.findall(r"^  (\S+)$", result.stdout + result.stderr, re.M))
            self.assertLessEqual({"apps/service/pyproject.toml", "apps/service/uv.lock"}, reported,
                                 result.stdout + result.stderr)
            # the Catch-up's steps settle it: the factory's side of each file, the own line back, the lock redone
            for name in ("pyproject.toml", "uv.lock"):
                subprocess.run(["git", "checkout", "--theirs", "--", f"apps/service/{name}"], cwd=repo, check=True,
                               capture_output=True, timeout=60)
            text = manifest.read_text(encoding="utf-8")
            self.assertIn(PIN, text)
            manifest.write_text(text.replace('  "ruff==0.16.3",\n', '  "ruff==0.16.3",\n  "iniconfig==2.1.0",\n', 1),
                                encoding="utf-8")
            done = subprocess.run(["uv", "lock", "--project", "apps/service"], cwd=repo, env=clean_environment(),
                                  text=True, capture_output=True, timeout=600)
            self.assertEqual(done.returncode, 0, done.stdout + done.stderr)
            checked = subprocess.run(["uv", "lock", "--check", "--project", "apps/service"], cwd=repo,
                                     env=clean_environment(), text=True, capture_output=True, timeout=300)
            self.assertEqual(checked.returncode, 0, checked.stdout + checked.stderr)

    def test_e3_a_wrapper_or_table_the_project_edited_is_not_overwritten_silently(self) -> None:
        """The existing `migrate` rule for a file the project owns, held with a mutmut file as the example."""
        with tempfile.TemporaryDirectory() as directory:
            repo = self.old_project(directory)
            own = repo / "/".join(WRAPPER)
            own.parent.mkdir(exist_ok=True)
            own.write_text("#!/usr/bin/env python3\n# the product's own mutation script\n", encoding="utf-8")
            commit_all(repo, "the product wired mutmut by hand")
            result = self.migrated(directory, repo)
            self.assertNotEqual(result.returncode, 0, "a file the project wrote was overwritten without a word")
            self.assertIn("scripts/mutmut-mutation.py", result.stdout + result.stderr)
            self.assertIn("the product's own mutation script", own.read_text(encoding="utf-8"))

    def test_e4_a_go_project_gains_no_mutmut_file_and_two_python_services_get_a_pin_and_a_table_each(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            repo = self.old_project(directory, "go")
            result = self.migrated(directory, repo)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertFalse((repo / "/".join(WRAPPER)).exists())
            self.assertNotIn("mutmut", " ".join(p.name for p in repo.rglob("*") if ".git" not in p.parts))
            self.assertNotIn("apps/*/mutants/", (repo / ".gitignore").read_text(encoding="utf-8"))
        with tempfile.TemporaryDirectory() as directory:
            repo = self.old_project(directory, "python", ("second",))
            result = self.migrated(directory, repo)
            # A service added by hand changed the lines the factory changed: its manifest and lock are listed for the
            # person to settle (the Catch-up says how), and the wrapper is merged once.
            self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
            reported = set(re.findall(r"^  (\S+)$", result.stdout + result.stderr, re.M))
            self.assertLessEqual({"apps/second/pyproject.toml", "apps/second/uv.lock"}, reported)
            for name in ("service", "second"):
                manifest = (repo / f"apps/{name}/pyproject.toml").read_text(encoding="utf-8")
                self.assertIn(PIN, manifest, name)
                self.assertIn("[tool.mutmut]", manifest, name)
            self.assertEqual(sorted(str(p.relative_to(repo)) for p in repo.rglob("mutmut-mutation*")
                                    if ".git" not in p.parts), ["scripts/mutmut-mutation.py"])


